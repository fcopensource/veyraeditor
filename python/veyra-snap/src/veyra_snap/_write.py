"""Write the recordings in ``.veyra-snap/`` as pytest files."""

from __future__ import annotations

import keyword
import os
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from . import _store

HEADER = "# Generated by veyra-snap from real calls: https://pypi.org/project/veyra-snap/"


@dataclass
class Written:
    path: Path
    module: str
    tests: int = 0
    cases: int = 0
    skipped: list[str] = field(default_factory=list)  # functions left out, and why
    kept: bool = False  # an existing file that isn't ours, left alone


def _ident(text: str) -> str:
    name = re.sub(r"\W+", "_", text).strip("_") or "fn"
    return name + "_" if keyword.iskeyword(name) else name


def _call_id(name: str, case: dict[str, Any]) -> str:
    inner = case["args"][1:-1].rstrip(",")
    if case["kwargs"] != "{}":
        inner = (inner + ", " if inner else "") + "**" + case["kwargs"]
    text = f"{name}({inner})"
    return text if len(text) <= 60 else text[:57] + "..."


def _lines(prefix: str, rows: list[str]) -> list[str]:
    return [f"{prefix}{row}," for row in rows]


def render(data: dict[str, Any], out_dir: Path, project: Path) -> tuple[str, int, int, list[str]]:
    """The test file for one recorded module: (source, tests, cases, functions left out)."""
    module = data["module"]
    imports = {f"import {module}"}
    blocks: list[str] = []
    tests = cases = 0
    skipped = []
    for qualname, fn in sorted(data["functions"].items()):
        if fn.get("nondeterministic"):
            skipped.append(f"{module}.{qualname}: gave different results for the same arguments")
            continue
        if not fn["cases"]:
            continue
        if all(c.get("returns") == "None" for c in fn["cases"]):
            # Nothing to check, and calling it again in a test would only repeat its side effects.
            skipped.append(f"{module}.{qualname}: only ever returned None")
            continue
        call = f"{module}.{qualname}"
        name = _ident(qualname)
        short = qualname.rsplit(".", 1)[-1]
        returns = [c for c in fn["cases"] if "raises" not in c]
        raises = [c for c in fn["cases"] if "raises" in c]
        for c in fn["cases"]:
            imports.update(c.get("imports", []))
            if "raises" in c and c["raises"]["import"]:
                imports.add(c["raises"]["import"])
        if returns:
            rows = [f"pytest.param({c['args']}, {c['kwargs']}, {c['returns']}, id={_call_id(short, c)!r})" for c in returns]
            blocks.append("\n".join([
                "@pytest.mark.parametrize(",
                '    "args, kwargs, expected",',
                "    [",
                *_lines("        ", rows),
                "    ],",
                ")",
                f"def test_{name}(args, kwargs, expected):",
                f"    assert {call}(*args, **kwargs) == expected",
            ]))
            tests += 1
        if raises:
            rows = [f"pytest.param({c['args']}, {c['kwargs']}, {c['raises']['type']}, {c['raises']['message']!r}, "
                    f"id={_call_id(short, c)!r})" for c in raises]
            blocks.append("\n".join([
                "@pytest.mark.parametrize(",
                '    "args, kwargs, error, message",',
                "    [",
                *_lines("        ", rows),
                "    ],",
                ")",
                f"def test_{name}_raises(args, kwargs, error, message):",
                "    with pytest.raises(error) as caught:",
                f"        {call}(*args, **kwargs)",
                "    assert str(caught.value) == message",
            ]))
            tests += 1
        cases += len(fn["cases"])
    if not blocks:
        return "", 0, 0, skipped

    root = project / data.get("root", "") if data.get("root") else project
    rel = os.path.relpath(root, out_dir).replace(os.sep, "/")
    path_parts = ", ".join(repr(p) for p in rel.split("/")) if rel != "." else ""
    head = [
        HEADER,
        "# Re-create it with `veyra-snap write`; changes made here are overwritten.",
        "import os",
        "import sys",
        "",
        "import pytest",
        "",
        "sys.path.insert(0, os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__))"
        + (f", {path_parts}" if path_parts else "") + ")))",
        "",
        *[f"{line}  # noqa: E402" for line in sorted(imports)],
    ]
    return "\n".join(head) + "\n\n\n" + "\n\n\n".join(blocks) + "\n", tests, cases, skipped


def write(project: str | os.PathLike[str] = ".", out: str = "tests", force: bool = False,
          only: list[str] | None = None) -> list[Written]:
    """Writes ``<out>/test_snap_<module>.py`` for every recorded module. Never overwrites a file it didn't write,
    unless ``force``."""
    project_path = Path(project).resolve()
    out_dir = (project_path / out).resolve()
    results = []
    for module, data in sorted(_store.load(_store.store_dir(project_path)).items()):
        if only and not any(module == m or module.startswith(m + ".") for m in only):
            continue
        path = out_dir / f"test_snap_{_ident(module)}.py"
        source, tests, cases, skipped = render(data, out_dir, project_path)
        result = Written(path, module, tests, cases, skipped)
        if not source:
            results.append(result)
            continue
        if path.exists() and not force:
            try:
                first = path.read_text(encoding="utf-8").split("\n", 1)[0]
            except OSError:
                first = ""
            if first != HEADER:
                result.kept = True
                results.append(result)
                continue
        out_dir.mkdir(parents=True, exist_ok=True)
        path.write_text(source, encoding="utf-8")
        results.append(result)
    return results
